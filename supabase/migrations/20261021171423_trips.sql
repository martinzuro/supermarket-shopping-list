-- =============================================================================
-- Past trips: what each emptying of the cart took (docs/improvements.md, F-4).
--
-- Emptying the cart archived the checked rows with one deleted_at, and so did
-- deleting a row that was in the cart: a trip of one product and a deletion
-- looked the same, so the list had no history to show. Now an emptying is a
-- row of its own, `trips`, and the rows it took point to it (items.trip_id).
-- Deleting a row never makes a trip.
--
--   * empty_cart archives the rows still in the cart and records the trip in
--     one transaction; restore_trip, the undo of the emptying (A-4), brings
--     the rows back and soft-deletes the trip. Both are idempotent: a retry
--     after a lost answer finds the work done.
--   * SECURITY DEFINER, so trips stay read-only for members, as the catalog
--     is: the history can only be what emptying the cart made. Each function
--     checks the caller's membership first and touches only that list's rows.
--   * items.trip_id points to a trip of the same list (a composite foreign
--     key, as items.category_id), and only these two functions change it: a
--     trigger refuses it to requests from the API, so nobody adds a row to a
--     trip, or takes one out of it, by hand.
--   * A merge (private.copy_list_into) copies the live rows only, as before:
--     the history stays with the list it was made in. Joining someone's list
--     does not show them what one bought before, and a list kept by a
--     carry-over starts its own.
--   * Not in the Realtime publication: the history is read when it is opened.
--   * No backfill: there are no real users yet (docs/plan.md), and an old
--     emptying cannot be told from a deletion. The history starts here.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- trips
-- -----------------------------------------------------------------------------

create table public.trips (
  -- Generated by the client, like every id (ADR 0003): a retry of the same
  -- emptying finds the trip it made.
  id uuid primary key,
  list_id uuid not null references public.lists (id) on delete cascade,
  -- When the cart was emptied: the archive time of its rows, the one the
  -- client showed and keeps across retries.
  emptied_at timestamptz not null,
  emptied_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Set when the emptying is undone: the history never shows it.
  deleted_at timestamptz,
  unique (list_id, id)
);

comment on table public.trips is
  'One emptying of a list''s cart (F-4): the rows it archived point to it through items.trip_id.';

-- The history reads a list's last trips, newest first.
create index trips_list_id_emptied_at_idx
on public.trips (list_id, emptied_at desc)
where deleted_at is null;

create trigger set_updated_at
before update on public.trips
for each row execute function private.set_updated_at();

alter table public.items
  add column trip_id uuid,
  add constraint items_trip_id_fkey foreign key (list_id, trip_id)
    references public.trips (list_id, id) on delete set null (trip_id);

comment on column public.items.trip_id is
  'The emptying of the cart that archived this row (F-4). Written only by empty_cart and restore_trip.';

create index items_trip_id_idx
on public.items (trip_id)
where trip_id is not null;

-- items.trip_id changes only inside empty_cart and restore_trip. Requests
-- from the API run as authenticated (or anon, which has no grants anyway);
-- those functions run as their owner, and so do migrations and the service
-- role's requests, which are not end users either.
create function private.guard_trip_id()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user in ('authenticated', 'anon')
    and (
      (tg_op = 'INSERT' and new.trip_id is not null)
      or (tg_op = 'UPDATE' and new.trip_id is distinct from old.trip_id)
    )
  then
    raise exception 'trip_id_read_only'
      using errcode = '42501',
        detail = 'Only emptying the cart, or undoing it, sets items.trip_id.';
  end if;
  return new;
end;
$$;

create trigger items_guard_trip_id
before insert or update of trip_id on public.items
for each row execute function private.guard_trip_id();

-- -----------------------------------------------------------------------------
-- empty_cart
-- -----------------------------------------------------------------------------
-- Archives the given rows of the list that are, when it runs, still live and
-- checked, all with emptied_at, and records them as the trip target_trip_id.
-- Returns the trip's rows.
--
--   * A row unchecked or archived meanwhile (by another member, or a check
--     the server rejected) stays where it is, as with the update this
--     replaces (useEmptyCart).
--   * Nothing left to archive, no trip: an emptying whose rows all left the
--     cart before it ran leaves nothing in the history.
--   * A retry after a lost answer finds the trip with its rows, archives
--     nothing more (they are not live any longer) and returns the same rows.
--     A trip already undone (restore_trip) archives nothing.
--   * Two members emptying at once: the second waits on the rows' locks and,
--     reading them again, finds them archived. Each row goes to one trip.
--
-- The caller's membership row is locked, as in merge_list: a removal waits
-- for the emptying.
--
-- Errors (stable keys, as in the sharing migration): not_authenticated
-- (42501), list_not_found (P0001), invalid_trip (22023).
create function public.empty_cart(
  target_list_id uuid,
  target_trip_id uuid,
  item_ids uuid[],
  emptied_at timestamptz
)
returns setof public.items
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  trip public.trips%rowtype;
begin
  if caller is null then
    raise exception 'not_authenticated'
      using errcode = '42501', detail = 'empty_cart requires a signed-in user.';
  end if;

  if target_trip_id is null or empty_cart.emptied_at is null then
    raise exception 'invalid_trip'
      using errcode = '22023', detail = 'A trip needs an id and a time.';
  end if;

  perform 1
  from public.list_members m
  join public.lists l on l.id = m.list_id
  where m.list_id = target_list_id
    and m.user_id = caller
    and l.deleted_at is null
  for share of m;
  if not found then
    raise exception 'list_not_found'
      using errcode = 'P0001', detail = 'The caller is not in this list.';
  end if;

  insert into public.trips (id, list_id, emptied_at, emptied_by)
  values (target_trip_id, target_list_id, empty_cart.emptied_at, caller)
  on conflict (id) do nothing;

  select t.* into trip
  from public.trips t
  where t.id = target_trip_id;

  if trip.list_id is distinct from target_list_id then
    -- Another list's trip: the client never reuses an id, so this is not one
    -- of its retries. Nothing is touched.
    raise exception 'invalid_trip'
      using errcode = '22023', detail = 'The trip belongs to another list.';
  end if;

  if trip.deleted_at is not null then
    -- Undone already: nothing to archive again.
    return;
  end if;

  update public.items i
  set deleted_at = empty_cart.emptied_at,
    trip_id = target_trip_id
  where i.list_id = target_list_id
    and i.id = any (item_ids)
    and i.deleted_at is null
    and i.checked;

  if not exists (
    select 1
    from public.items i
    where i.list_id = target_list_id
      and i.trip_id = target_trip_id
  ) then
    -- Nothing went to this trip: it is not kept.
    delete from public.trips t
    where t.id = target_trip_id;
    return;
  end if;

  return query
  select i.*
  from public.items i
  where i.list_id = target_list_id
    and i.trip_id = target_trip_id
  order by i.position, i.created_at, i.id;
end;
$$;

-- -----------------------------------------------------------------------------
-- restore_trip
-- -----------------------------------------------------------------------------
-- Undoes an emptying (A-4's "Deshacer"): the rows the trip took go back to
-- the cart, live and still checked, out of the trip, and the trip is
-- soft-deleted, so the history never shows an emptying that was undone.
-- Returns the rows that came back.
--
--   * A trip that does not exist, or that is not of a live list of the
--     caller, changes nothing and returns nothing. The first is the undo of
--     an emptying that never reached the server (undone before it left the
--     list's queue); nothing tells the two apart.
--   * A retry after a lost answer finds the rows back and the trip deleted:
--     nothing changes and nothing is returned.
create function public.restore_trip(target_trip_id uuid)
returns setof public.items
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  trip_list_id uuid;
begin
  if caller is null then
    raise exception 'not_authenticated'
      using errcode = '42501', detail = 'restore_trip requires a signed-in user.';
  end if;

  select t.list_id into trip_list_id
  from public.trips t
  where t.id = target_trip_id;

  perform 1
  from public.list_members m
  join public.lists l on l.id = m.list_id
  where m.list_id = trip_list_id
    and m.user_id = caller
    and l.deleted_at is null
  for share of m;
  if not found then
    return;
  end if;

  update public.trips t
  set deleted_at = now()
  where t.id = target_trip_id
    and t.deleted_at is null;

  return query
  with restored as (
    update public.items i
    set deleted_at = null,
      trip_id = null
    where i.list_id = trip_list_id
      and i.trip_id = target_trip_id
    returning i.*
  )
  select r.*
  from restored r
  order by r.position, r.created_at, r.id;
end;
$$;

-- -----------------------------------------------------------------------------
-- Row Level Security and privileges
-- -----------------------------------------------------------------------------
-- Members read their lists' trips; nobody writes them but the two functions
-- above. No update grant: a trip's list never changes.

alter table public.trips enable row level security;

create policy "Members can read their lists' trips"
on public.trips for select to authenticated
using (private.is_list_member(list_id));

revoke all on table public.trips from anon, authenticated;
grant select on table public.trips to authenticated;

revoke all on function public.empty_cart(uuid, uuid, uuid[], timestamptz)
from public, anon;
grant execute on function public.empty_cart(uuid, uuid, uuid[], timestamptz)
to authenticated;

revoke all on function public.restore_trip(uuid) from public, anon;
grant execute on function public.restore_trip(uuid) to authenticated;

revoke all on function private.guard_trip_id()
from public, anon, authenticated;
